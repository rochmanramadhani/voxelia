/** Resolve the 'auto' setting against the browser's own language list. */
function detectLocale() {
  const list = navigator.languages && navigator.languages.length
    ? navigator.languages : [navigator.language || 'en'];
  for (const l of list) {
    const tag = String(l).toLowerCase();
    if (tag.startsWith('id') || tag.startsWith('in')) return 'id';   // "in" = kode ISO lama
    if (tag.startsWith('en')) return 'en';
  }
  return 'en';
}

function setLocale(pref) {
  LOCALE = (pref && pref !== 'auto' && LOCALES.indexOf(pref) >= 0) ? pref : detectLocale();
  document.documentElement.lang = LOCALE;
  return LOCALE;
}

/** Look up a key, substituting {placeholders}. Falls back en -> key. */
function t(key, vars) {
  const dict = I18N[LOCALE] || I18N.en;
  let s = dict[key];
  if (s === undefined) s = I18N.en[key];
  if (s === undefined) return key;
  if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  return s;
}

/** Apply every data-i18n binding under `root`. */
function applyI18n(root) {
  root = root || document;
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
  root.querySelectorAll('[data-i18n-title]').forEach(el => el.setAttribute('title', t(el.dataset.i18nTitle)));
}
